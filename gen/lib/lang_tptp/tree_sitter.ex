defmodule LangTptp.TreeSitter do
  @moduledoc """
  Prints the IR as a tree-sitter `grammar.js`.

  The translation is mechanical:

    * `TPTP_file` comes first, since tree-sitter starts from the first rule.
    * Transparent rules (every alternative has exactly one child) are hidden with a
      `_` prefix, so the tree stays close to the size of the input.
    * `<nothing>` alternatives are dropped and every use of a nullable rule is
      wrapped in `optional(…)`, because tree-sitter rejects rules that match the
      empty string.
    * Value tokens become regex rules printed by `LangTptp.Regex.to_js/1`; literal
      spellings become strings, and `word: $ => $.lower_word` turns the lower-case
      ones into keywords.
    * Whitespace and the BNF's `<comment>` are `extras`.

  Departures from that translation are the module attributes below, listed by
  `departures/0`.
  """

  alias LangTptp.IR
  alias LangTptp.Regex, as: Re

  # Pairs of rules whose LR(1) conflict tree-sitter resolves at runtime (GLR).
  @conflicts []

  # The source keywords are also admitted as <atomic_word>, as in `tptp`'s yecc
  # grammar. With `word` set, tree-sitter lexes `file` as the keyword wherever the
  # keyword is valid, which includes every <source> position, so without this
  # `[file, inference]` as a parent list would not parse. Aliased to `lower_word`
  # so the tree looks the same as for any other word.
  @keywords_as_words ~w(inference introduced file)
  @keywords_as_words_rule "atomic_word"

  @doc "One line per departure from a mechanical translation."
  @spec departures() :: [binary()]
  def departures do
    [
      "admitted the keywords #{Enum.join(@keywords_as_words, ", ")} as <#{@keywords_as_words_rule}> " <>
        "(aliased to lower_word)"
    ] ++
      for names <- @conflicts do
        "declared conflict: " <> Enum.join(names, " / ")
      end
  end

  @doc "The rule name tree-sitter uses for a BNF nonterminal or token."
  @spec name(IR.t(), binary()) :: binary()
  def name(%IR{} = ir, bnf_name) do
    if MapSet.member?(ir.transparent, bnf_name), do: "_" <> bnf_name, else: bnf_name
  end

  @doc "Render `grammar.js`."
  @spec render(IR.t()) :: binary()
  def render(%IR{} = ir) do
    {root, rest} = Enum.split_with(ir.rules, fn {name, _} -> name == ir.root end)

    rules =
      Enum.map(root ++ rest, fn {bnf_name, alts} -> rule(ir, bnf_name, alts) end) ++
        Enum.map(ir.token_order, &token_rule(ir, &1))

    """
    /**
     * @file TPTP grammar for tree-sitter, generated from the TPTP SyntaxBNF
     * @author Johannes Schuster <johannes.c.schuster@proton.me>
     * @license MIT
     */

    // Generated by `mix lang_tptp.gen` from SyntaxBNF-v#{ir.version}. Do not edit.

    /// <reference types="tree-sitter-cli/dsl" />
    // @ts-check

    export default grammar({
      name: "tptp",

      extras: $ => [/\\s/, $.comment],

      word: $ => $.lower_word,

      conflicts: $ => [#{render_conflicts(ir)}],

      rules: {
    #{Enum.join(rules, ",\n\n")},

        comment: _ => token(/#{Re.to_js(Map.fetch!(ir.tokens, "comment"))}/),
      },
    });
    """
  end

  defp render_conflicts(ir) do
    Enum.map_join(@conflicts, fn names ->
      "\n    [" <> Enum.map_join(names, ", ", &("$." <> name(ir, &1))) <> "],"
    end) <> "\n  "
  end

  defp rule(ir, bnf_name, alts) do
    non_empty = Enum.reject(alts, &(&1 == []))

    body =
      case Enum.map(non_empty, &alternative(ir, &1)) ++ injected(bnf_name) do
        [single] -> single
        many -> "choice(\n" <> Enum.map_join(many, ",\n", &("      " <> &1)) <> ",\n    )"
      end

    "    #{name(ir, bnf_name)}: $ => #{body}"
  end

  defp injected(@keywords_as_words_rule) do
    for word <- @keywords_as_words, do: "alias(#{JSON.encode!(word)}, $.lower_word)"
  end

  defp injected(_bnf_name), do: []

  defp alternative(ir, [single]), do: symbol(ir, single)

  defp alternative(ir, symbols),
    do: "seq(" <> Enum.map_join(symbols, ", ", &symbol(ir, &1)) <> ")"

  defp symbol(ir, {:nt, n}) do
    ref = "$." <> name(ir, n)
    if MapSet.member?(ir.nullable, n), do: "optional(#{ref})", else: ref
  end

  defp symbol(_ir, {:token, n}), do: "$." <> n
  defp symbol(_ir, {:lit, s}), do: JSON.encode!(s)
  defp symbol(ir, {:repeat, sym}), do: "repeat(#{symbol(ir, sym)})"

  defp token_rule(ir, n), do: "    #{n}: _ => /#{Re.to_js(Map.fetch!(ir.tokens, n))}/"
end
