defmodule LangTptp.Lezer do
  @moduledoc """
  Prints the IR as a Lezer grammar (`tptp.grammar`).

  The translation follows `LangTptp.TreeSitter`:

    * Visible rules get CamelCase node names (`thf_annotated` → `ThfAnnotated`);
      transparent rules get lower-case names, which Lezer does not put in the tree.
    * `<nothing>` alternatives are dropped and uses of nullable rules get `?`.
    * Value tokens and the comment go into `@tokens`, printed by
      `LangTptp.Regex.to_lezer/1`; every punctuation and operator spelling is listed
      there too, so each gets a node named after its text.
    * Word spellings are written as specialisations of the word token they would
      otherwise lex as; see the departures.
  """

  alias LangTptp.IR
  alias LangTptp.Regex, as: Re

  # Words that are keywords in one position and ordinary names in another
  # (`fof(fof, axiom, p).`, `[file, inference]` as parents). `@extend` keeps both
  # readings and lets the GLR parser pick, as the outline's §3.4 expects.
  @extended ~w(thf tff tcf fof cnf tpi include inference introduced file)

  # `$`-words that are reserved, as in `tptp`'s yecc grammar: `$let(a, b, c)` would
  # otherwise be both a <thf_let> and a defined function application.
  @specialized ~w($thf $tff $fof $cnf $fot $let)

  @doc "One line per departure from a mechanical translation."
  @spec departures(IR.t()) :: [binary()]
  def departures(%IR{} = ir) do
    {left, lists} = repetitions(ir)

    [
      "@extend (keyword or word): #{Enum.join(@extended, " ")}",
      "@specialize (reserved $-words): #{Enum.join(@specialized, " ")}",
      "left recursion printed as repetition (#{length(left)}): #{Enum.join(left, " ")}",
      "right-recursive lists printed as repetition (#{length(lists)}): #{Enum.join(lists, " ")}"
    ]
  end

  # Lezer stops making left-associative reductions after a few hundred in a row and
  # reports an error, which a long `&` chain in one statement reaches. Its documented
  # remedy is repetition, which it also stores as balanced subtrees. So
  # `R ::= β | R α` is printed as `β α*`, and the list shape `R ::= x | x s R` as
  # `x (s x)*`. Both accept the same language; only the tree is flatter.
  defp repetitions(ir) do
    shapes = for {n, alts} <- ir.rules, shape = recursion(n, alts), do: {elem(shape, 0), n}
    {for({:left, n} <- shapes, do: n), for({:list, n} <- shapes, do: n)}
  end

  defp recursion(name, alts) do
    alts = Enum.reject(alts, &(&1 == []))
    self = {:nt, name}
    {left, base} = Enum.split_with(alts, &match?([^self | _], &1))

    cond do
      left != [] and base != [] and not Enum.any?(base, &(self in &1)) and
          not Enum.any?(left, &(self in tl(&1))) ->
        {:left, base, Enum.map(left, &tl/1)}

      match?([_, _], alts) ->
        [a, b] = Enum.sort_by(alts, &length/1)
        k = length(a)

        if self not in a and Enum.take(b, k) == a and List.last(b) == self and length(b) > k + 1 and
             self not in Enum.slice(b, k..-2//1) do
          {:list, a, Enum.slice(b, k..-2//1)}
        end

      true ->
        nil
    end
  end

  @doc "The Lezer node or rule name for a BNF nonterminal or token."
  @spec name(IR.t(), binary()) :: binary()
  def name(%IR{} = ir, bnf_name) do
    cond do
      bnf_name == "comment" -> "Comment"
      MapSet.member?(ir.transparent, bnf_name) -> String.downcase(bnf_name)
      true -> camel(bnf_name)
    end
  end

  defp camel(bnf_name) do
    bnf_name
    |> String.split("_")
    |> Enum.map_join(fn <<first::utf8, rest::binary>> ->
      String.upcase(<<first::utf8>>) <> rest
    end)
  end

  @doc "The node name Lezer gives a literal spelling."
  @spec literal_name(binary()) :: binary()
  def literal_name(spelling), do: spelling

  @doc "Render `tptp.grammar`."
  @spec render(IR.t()) :: binary()
  def render(%IR{} = ir) do
    check_words!(ir)

    {[{root, root_alts}], rest} = Enum.split_with(ir.rules, fn {n, _} -> n == ir.root end)

    rules = Enum.map_join(rest, "\n\n", fn {n, alts} -> rule(ir, n, alts) end)

    punctuation =
      ir.literals
      |> Enum.reject(&IR.word?/1)
      |> Enum.map_join(" ", &lezer_literal/1)

    tokens =
      Enum.map_join(ir.token_order, "\n\n", fn n ->
        "  #{name(ir, n)} { #{Re.to_lezer(Map.fetch!(ir.tokens, n))} }"
      end)

    """
    // Generated by `mix lang_tptp.gen` from SyntaxBNF-v#{ir.version}. Do not edit.

    @top #{name(ir, root)} { #{body(ir, root_alts)} }

    @skip { space | Comment }

    #{rules}

    @tokens {
      space { $[ \\t\\n\\r]+ }

      @precedence { #{precedence(ir)} }

      Comment { #{Re.to_lezer(Map.fetch!(ir.tokens, "comment"))} }

    #{tokens}

      #{punctuation}
    }

    @external propSource tptpHighlighting from "./highlight"

    @detectDelim
    """
  end

  # The `@extend`/`@specialize` lists must cover exactly the words the grammar uses.
  defp check_words!(ir) do
    listed = Enum.sort(@extended ++ @specialized)

    if listed != ir.keywords do
      raise ArgumentError,
            "LangTptp.Lezer lists the words #{inspect(listed)} but the grammar uses #{inspect(ir.keywords)}"
    end
  end

  # Tokens that are prefixes of each other (`+0` and `+0.0`, `$` and `$$`) need an
  # order; longest match still applies, the order only settles equal-length matches.
  @token_precedence ~w(real rational integer dollar_dollar_word dollar_word)

  defp precedence(ir), do: Enum.map_join(@token_precedence, ", ", &name(ir, &1))

  defp rule(ir, bnf_name, alts) do
    body =
      case recursion(bnf_name, alts) do
        {:left, base, tails} ->
          group(ir, base) <> " " <> group(ir, tails, true) <> "*"

        {:list, item, sep} ->
          alternative(ir, item) <> " " <> group(ir, [sep ++ item], true) <> "*"

        nil ->
          body(ir, alts)
      end

    "#{name(ir, bnf_name)} { #{body} }"
  end

  defp group(ir, alts, always \\ false) do
    text = body(ir, alts)
    if always or match?([_, _ | _], alts), do: "(#{text})", else: text
  end

  defp body(ir, alts) do
    alts
    |> Enum.reject(&(&1 == []))
    |> Enum.map_join(" | ", &alternative(ir, &1))
  end

  defp alternative(ir, symbols), do: Enum.map_join(symbols, " ", &symbol(ir, &1))

  defp symbol(ir, {:nt, n}) do
    if MapSet.member?(ir.nullable, n), do: name(ir, n) <> "?", else: name(ir, n)
  end

  defp symbol(ir, {:token, n}), do: name(ir, n)
  defp symbol(ir, {:repeat, sym}), do: wrap(symbol(ir, sym)) <> "*"
  defp symbol(ir, {:lit, s}), do: literal(ir, s)

  defp wrap(text), do: if(String.ends_with?(text, "?"), do: "(#{text})", else: text)

  defp literal(ir, word) when word in @extended do
    "@extend[@name=#{word}]<#{name(ir, "lower_word")}, #{lezer_literal(word)}>"
  end

  defp literal(ir, word) when word in @specialized do
    "@specialize[@name=#{JSON.encode!(word)}]<#{name(ir, "dollar_word")}, #{lezer_literal(word)}>"
  end

  defp literal(_ir, spelling), do: lezer_literal(spelling)

  defp lezer_literal(spelling), do: JSON.encode!(spelling)
end
